def _main(argv: Optional[list[str]] = None) -> int:
    import argparse

    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--root",
        type=Path,
        default=Path.home() / ".autoresearchclaw" / "specimens",
    )
    p.add_argument("--out", type=Path, default=None)
    p.add_argument(
        "--filter",
        choices=("all", "mesh", "ct", "skull"),
        default="all",
    )
    p.add_argument("--project-query", default="Colors of Skull Anatomy")
    p.add_argument("--summary", action="store_true",
                   help="Print a one-line per-specimen summary instead of "
                        "writing a manifest")
    args = p.parse_args(argv)

    specs = scan_specimens(args.root)
    if args.filter == "mesh":
        specs = [s for s in specs if s.kind == "mesh"]
    elif args.filter == "ct":
        specs = [s for s in specs if s.kind == "ct"]
    elif args.filter == "skull":
        specs = filter_skull_meshes(specs)

    if args.summary:
        for s in specs:
            print(json.dumps(s.to_summary_dict()))
        return 0

    if args.out is None:
        print(json.dumps(
            {"specimens": [s.to_manifest_entry(project_query=args.project_query)
                           for s in specs]},
            indent=2,
        ))
        return 0

    write_manifest(args.out, specs, project_query=args.project_query)
    print(f"Wrote {len(specs)} specimens to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(_main())
